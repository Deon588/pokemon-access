local check = require("check")
local bit = require("compat.bit")

check.eq(bit.band(0xff, 0x0f), 15, "band")
check.eq(bit.bor(0xf0, 0x0f), 255, "bor")
check.eq(bit.bxor(0xff, 0x0f), 0xf0, "bxor")
check.eq(bit.lshift(1, 4), 16, "lshift")
check.eq(bit.rshift(0x80, 7), 1, "rshift")
check.eq(bit.bnot(0), -1, "bnot gives a signed 32-bit result")
check.eq(bit.lshift(1, 31), -2147483648, "lshift wraps to signed 32-bit")
check.eq(bit.rshift(-1, 28), 15, "rshift treats the input as unsigned 32-bit")
check.eq(bit.arshift(-16, 2), -4, "arshift keeps the sign")
check.eq(bit.tobit(0xffffffff), -1, "tobit")
check.eq(bit.tohex(255), "000000ff", "tohex")
check.eq(bit.band(255.0, 15), 15, "floats are accepted")
check.eq(bit.band(0x1234, 0xff00), 0x1200, "band masks")
check.eq(bit.band(0xff, 0x0f, 0x03), 3, "band takes more than two arguments")
check.done()
